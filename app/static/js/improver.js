/* Prompt Improver: calls the local rule-based improver and renders the comparison. */
(function () {
  "use strict";
  var PCH = window.PCH;
  var form = document.getElementById("improve-form");
  if (!form) return;
  var $ = function (id) { return document.getElementById(id); };
  var area = $("prompt"), result = $("result"), improved = "", original = "", last = null;
  var SAMPLES = ["Write an email.", "Summarize the meeting notes.", "Write a SQL query to find duplicate customers.", "Make a project plan."];
  var sampleIdx = 0;

  function counter() { $("char-count").textContent = area.value.length.toLocaleString(); }
  area.addEventListener("input", counter); counter();

  function options() {
    var o = { purpose: $("o-purpose").value || null, audience: $("o-audience").value.trim(), ai_tool: $("o-tool").value, output_type: $("o-format").value,
      tone: $("o-tone").value.trim(), word_limit: $("o-words").value.trim(), detail_level: $("o-detail").value };
    return o;
  }

  function list(el, items, empty) {
    el.innerHTML = "";
    if (!items.length) { el.appendChild(PCH.el("li", { "class": "muted", text: empty })); return; }
    items.forEach(function (t) { el.appendChild(PCH.el("li", { text: t })); });
  }

  function showScores(before, after, labelB, labelA) {
    $("ring-before").innerHTML = PCH.scoreRing(before, "", labelB);
    $("ring-after").innerHTML = PCH.scoreRing(after, "", labelA);
    $("score-summary").innerHTML = "Score <strong>" + before + "</strong> (" + PCH.escape(labelB) + ") &rarr; <strong>" + after + "</strong> (" + PCH.escape(labelA) + "), a change of <strong>" + (after - before >= 0 ? "+" : "") + (after - before) + "</strong> points.";
  }

  function render(r) {
    last = r; improved = r.improved; original = r.original;
    result.hidden = false;
    $("orig-text").textContent = r.original;
    $("imp-text").textContent = r.improved; $("imp-text").hidden = false; $("imp-edit").hidden = true; $("edit-actions").hidden = true;
    showScores(r.original_score, r.improved_score, r.original_label, r.improved_label);
    $("provider-note").textContent = "Generated by: " + r.provider_label + (r.use_case_label ? " | Detected type: " + r.use_case_label : "");
    list($("missing-list"), r.missing_components || [], "Nothing important was missing.");
    list($("notes-list"), r.notes || [], "No extra notes.");
    $("placeholder-note").innerHTML = (r.placeholders && r.placeholders.length)
      ? '<p class="small muted">Fill in: ' + r.placeholders.map(function (p) { return '<span class="ph">[' + PCH.escape(p) + ']</span>'; }).join(" ") + "</p>" : "";
    var ch = $("changes"); ch.innerHTML = "";
    (r.changes || []).forEach(function (c) {
      var d = PCH.el("div", { "class": "change" });
      d.innerHTML = '<span class="badge badge-cat">' + PCH.escape(String(c.component).replace(/_/g, " ")) + '</span> <span class="badge">' + PCH.escape(c.type || "") + '</span>';
      d.appendChild(PCH.el("p", { style: "margin:.35rem 0 .1rem", text: c.change }));
      d.appendChild(PCH.el("p", { "class": "why", text: "Why it helps: " + c.why }));
      ch.appendChild(d);
    });
    if (!ch.children.length) ch.appendChild(PCH.el("p", { "class": "muted", text: "No changes were needed." }));
    $("breakdown").innerHTML = r.improved_quality ? PCH.breakdownHtml(r.improved_quality.breakdown) : "";
    result.scrollIntoView({ behavior: "smooth", block: "start" });
  }

  function run(text) {
    var err = $("prompt-error");
    if (!text.trim()) { PCH.fieldError(area, err, "Enter a prompt to improve."); area.focus(); return; }
    PCH.fieldError(area, err, "");
    var btn = $("improve-btn"); PCH.busy(btn, true, "Improving...");
    PCH.post("/api/prompts/improve", { prompt: text, options: options() })
      .then(render, function (e) { PCH.fieldError(area, err, PCH.errorText(e)); PCH.toast(PCH.errorText(e), "error"); })
      .then(function () { PCH.busy(btn, false); });
  }
  form.addEventListener("submit", function (e) { e.preventDefault(); run(area.value); });
  $("sample-btn").addEventListener("click", function () { area.value = SAMPLES[sampleIdx++ % SAMPLES.length]; counter(); area.focus(); });
  $("clear-btn").addEventListener("click", function () { area.value = ""; counter(); result.hidden = true; PCH.fieldError(area, $("prompt-error"), ""); area.focus(); });
  $("restart-btn").addEventListener("click", function () { $("clear-btn").click(); window.scrollTo({ top: 0, behavior: "smooth" }); });

  $("copy-btn").addEventListener("click", function () { PCH.copy(improved, "Improved prompt copied."); });
  $("edit-btn").addEventListener("click", function () {
    $("imp-edit").value = improved; $("imp-edit").hidden = false; $("imp-text").hidden = true; $("edit-actions").hidden = false; $("imp-edit").focus();
  });
  $("cancel-edit").addEventListener("click", function () { $("imp-edit").hidden = true; $("imp-text").hidden = false; $("edit-actions").hidden = true; });
  $("rescore-btn").addEventListener("click", function () {
    var text = $("imp-edit").value.trim(); if (!text) { PCH.toast("The prompt cannot be empty.", "error"); return; }
    var btn = $("rescore-btn"); PCH.busy(btn, true, "Scoring...");
    PCH.post("/api/prompts/analyze", { prompt: text }).then(function (a) {
      improved = text; $("imp-text").textContent = text; $("imp-edit").hidden = true; $("imp-text").hidden = false; $("edit-actions").hidden = true;
      showScores(last.original_score, a.score, last.original_label, a.label); $("breakdown").innerHTML = PCH.breakdownHtml(a.breakdown);
      PCH.toast("Edits applied and re-scored.", "success");
    }, function (e) { PCH.toast(PCH.errorText(e), "error"); }).then(function () { PCH.busy(btn, false); });
  });
  $("save-btn").addEventListener("click", function () {
    PCH.ask("Name for this prompt", original.replace(/\s+/g, " ").slice(0, 50) + " (improved)", { title: "Save improved prompt" }).then(function (title) {
      if (!title) return;
      PCH.post("/api/custom-prompts", { title: title, description: "Improved with the Prompt Improver.", content: improved, origin: "improver", tags: ["improved"] })
        .then(function () { PCH.toast("Saved to My Prompts.", "success"); }, function (e) { PCH.toast(PCH.errorText(e), "error"); });
    });
  });
  document.querySelectorAll("[data-export]").forEach(function (b) {
    b.addEventListener("click", function () { PCH.exportPrompt(original.replace(/\s+/g, " ").slice(0, 50) + " improved", improved, b.dataset.export); });
  });
  $("to-diagnostic").addEventListener("click", function () { PCH.handoff.set("diagnose", improved); });

  var h = PCH.handoff.take("improve");
  if (h) { area.value = h; counter(); run(h); }
})();

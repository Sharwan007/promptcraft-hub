USE_CASE_ORDER = [k for k in PROFILES if k != "general"]
_COMPILED = {k: re.compile(v["pattern"], re.IGNORECASE) for k, v in PROFILES.items() if k != "general"}
# More specific profiles are checked before generic ones.
DETECTION_ORDER = [
    "acceptance_criteria", "user_stories", "meeting_minutes", "root_cause", "risk", "sql", "excel",
    "presentation", "customer_response", "email", "summary", "code", "project_plan", "research",
    "marketing", "analysis", "report", "brainstorm",
]


def detect_use_case(text: str) -> str:
    for key in DETECTION_ORDER:
        if _COMPILED[key].search(text or ""):
            return key
    return "general"


def get_profile(key: str | None) -> dict:
    return PROFILES.get(key or "general", PROFILES["general"])


def use_case_choices() -> list[dict]:
    return [{"key": k, "label": PROFILES[k]["label"]} for k in PROFILES]
